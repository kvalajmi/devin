#!/bin/bash

# سكريبت تشغيل سريع لحذف جميع البيانات
# يمكن تشغيله بالأمر: ./run-clear-data.sh

echo "🗑️ سكريبت حذف جميع البيانات من النظام"
echo "========================================"
echo ""

# التحقق من وجود Node.js
if ! command -v node &> /dev/null; then
    echo "❌ خطأ: Node.js غير مثبت على النظام"
    echo "يرجى تثبيت Node.js أولاً من: https://nodejs.org"
    exit 1
fi

# التحقق من وجود ملف السكريبت
if [ ! -f "clear-database-simple.js" ]; then
    echo "❌ خطأ: ملف clear-database-simple.js غير موجود"
    echo "تأكد من تشغيل هذا الأمر في مجلد المشروع الصحيح"
    exit 1
fi

# عرض تحذير
echo "⚠️  تحذير مهم:"
echo "هذا السكريبت سيحذف جميع البيانات التالية نهائياً:"
echo "• جميع العملاء وبياناتهم"
echo "• جميع الدفعات والمعاملات"
echo "• جميع المصروفات وأتعاب المحاماة"
echo "• جميع سحوبات المستثمرين والشركاء"
echo "• جميع سجلات التمويل الفعلي"
echo "• جميع المرفقات والوثائق"
echo ""

# طلب التأكيد
read -p "هل أنت متأكد من أنك تريد المتابعة؟ (اكتب 'نعم' للتأكيد): " confirmation

if [ "$confirmation" != "نعم" ]; then
    echo "❌ تم إلغاء العملية"
    exit 0
fi

echo ""
echo "🚀 بدء عملية الحذف..."
echo ""

# تشغيل سكريبت الحذف
node clear-database-simple.js

# التحقق من نتيجة التشغيل
if [ $? -eq 0 ]; then
    echo ""
    echo "🎉 تم تشغيل سكريبت الحذف بنجاح!"
    echo "راجع النتائج أعلاه للتأكد من اكتمال العملية"
else
    echo ""
    echo "❌ حدث خطأ أثناء تشغيل سكريبت الحذف"
    echo "راجع رسائل الخطأ أعلاه"
    exit 1
fi
